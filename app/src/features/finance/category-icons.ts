export const CATEGORY_ICON_OPTIONS: readonly CategoryIconOption[] = seeds.flatMap(
  ([key, label, keywords, component, path]) => [
    { key, label, keywords, series: 'outline' as const, component },
    { key: `filled:${key}`, label, keywords, series: 'filled' as const, path },
  ],
)

const iconMap = new Map(CATEGORY_ICON_OPTIONS.map((icon) => [icon.key, icon]))

export function findCategoryIcon(iconKey?: string): CategoryIconOption {
  return iconMap.get(iconKey ?? '') ?? iconMap.get('circle-ellipsis')!
}
